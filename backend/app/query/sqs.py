"""
SENTINEL AI — Sentinel Query Specification (SQS).

Typed query representation generated by planner or user and validated
before execution against any SIEM provider.
Strict Pydantic v2 models with extra="forbid".
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class FilterOperator(StrEnum):
    EQ = "eq"
    IN = "in"
    CONTAINS = "contains"
    GTE = "gte"
    LTE = "lte"
    GT = "gt"
    LT = "lt"
    EXISTS = "exists"


class AggregationType(StrEnum):
    TERMS = "terms"
    DATE_HISTOGRAM = "date_histogram"
    VALUE_COUNT = "value_count"


class TimeRange(BaseModel):
    model_config = ConfigDict(extra="forbid")

    start: datetime
    end: datetime

    @model_validator(mode="after")
    def validate_time_order(self) -> TimeRange:
        if self.start >= self.end:
            raise ValueError(f"TimeRange start ({self.start}) must be before end ({self.end})")
        return self


class QueryFilter(BaseModel):
    model_config = ConfigDict(extra="forbid")

    field: str
    operator: FilterOperator
    value: str | int | float | bool | list[str] | None = None

    @model_validator(mode="after")
    def validate_operator_value(self) -> QueryFilter:
        if self.operator == FilterOperator.EXISTS:
            # Value is not needed for exists
            return self
        if self.operator == FilterOperator.IN and not isinstance(self.value, list):
            raise ValueError(
                f"Filter with 'in' operator must have a list value, got {type(self.value)}"
            )
        if self.value is None and self.operator != FilterOperator.EXISTS:
            raise ValueError(f"Filter operator '{self.operator}' requires a non-null value")
        return self


class QueryAggregation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    type: AggregationType
    field: str
    interval: str | None = None
    size: int | None = None


class SentinelQuerySpec(BaseModel):
    """
    Canonical Sentinel Query Specification (SQS).

    Strict Pydantic v2 specification with extra="forbid".
    All SIEM searches are planned in this representation.
    """
    model_config = ConfigDict(extra="forbid")

    provider: Literal["synthetic", "elasticsearch", "wazuh"] = "synthetic"
    time_range: TimeRange
    filters: list[QueryFilter] = Field(default_factory=list)
    aggregations: list[QueryAggregation] = Field(default_factory=list)
    sort_field: str = "@timestamp"
    sort_order: Literal["asc", "desc"] = "desc"
    page_size: int = 100
    cursor: str | None = None
    requested_fields: list[str] = Field(default_factory=list)
    intent: str
